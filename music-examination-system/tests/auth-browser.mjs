import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { fixture } from './auth-fixture.mjs';

const f = await fixture();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const password = 'MusicExam123!';
const errors = [];
await mkdir('qa/auth', { recursive: true });
try {
  for (const role of ['student', 'parent']) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${f.base}/register`);
    await page.getByRole('button', { name: `Register as ${role === 'student' ? 'Student' : 'Parent'}` }).click();
    assert.equal(await page.locator('form input').count(), 3);
    await page.locator('input[name="name"]').fill('Music Applicant');
    await page.locator('input[name="email"]').fill(`${role}@example.test`);
    await page.locator('input[name="password"]').fill(password);
    await page.getByRole('button', { name: 'Register', exact: true }).click();
    await page.waitForURL('**/verify-email');
    await page.getByText(`${role}@example.test`, { exact: true }).waitFor();
    const code = f.messages.at(-1).code;
    assert.ok(code); assert.ok(!(await page.locator('body').innerText()).includes(code));
    await page.reload();
    await page.getByRole('region', { name: `${role === 'student' ? 'Student' : 'Parent'} email verification` }).waitFor();
    await page.getByLabel('Verification Code', { exact: true }).fill('000000');
    await page.getByRole('button', { name: 'VERIFY', exact: true }).click();
    await page.getByText('Invalid verification code', { exact: true }).waitFor();
    await page.getByLabel('Verification Code', { exact: true }).fill('');
    await page.screenshot({ path: `qa/auth/${role}-verification.png`, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `qa/auth/${role}-verification-mobile.png`, fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByLabel('Verification Code', { exact: true }).fill(code);
    await page.getByRole('button', { name: 'VERIFY', exact: true }).click();
    await page.waitForURL(`**/${role}/dashboard`);
    await page.screenshot({ path: `qa/auth/${role}-dashboard.png`, fullPage: true });
    const local = await page.evaluate(() => JSON.stringify(localStorage));
    assert.ok(!local.includes(password)); assert.ok(!local.includes('music_auth')); assert.ok(!local.includes('"verified"'));
    await page.goto(`${f.base}/${role === 'student' ? 'parent' : 'student'}/dashboard`);
    await page.waitForURL(`**/${role}/dashboard`);
    const login = await browser.newContext(); const loginPage = await login.newPage();
    await loginPage.goto(`${f.base}/login`);
    assert.equal(await loginPage.locator('form input').count(), 0);
    await loginPage.getByRole('button', { name: role === 'student' ? 'Parent' : 'Student', exact: true }).click();
    await loginPage.getByLabel('Email Address', { exact: true }).fill(`${role}@example.test`);
    await loginPage.getByLabel('Password', { exact: true }).fill(password);
    await loginPage.getByRole('button', { name: 'Log in', exact: true }).click();
    await loginPage.getByText('Selected role does not match your account type.', { exact: true }).waitFor();
    await loginPage.getByRole('button', { name: role === 'student' ? 'Student' : 'Parent', exact: true }).click();
    await loginPage.getByRole('button', { name: 'Log in', exact: true }).click();
    await loginPage.waitForURL(`**/${role}/dashboard`);
    await login.close(); await context.close();
    console.log(`${role}: registration, SMTP, refresh, wrong/correct OTP, dashboard, login and cross-role routing passed`);
  }
  const context = await browser.newContext(); const page = await context.newPage();
  await page.goto(`${f.base}/student/dashboard`); await page.waitForURL('**/login');
  await page.goto(`${f.base}/register`);
  await page.getByRole('button', { name: 'Register', exact: true }).click();
  await page.getByText('Full legal name is required.', { exact: true }).waitFor();
  await page.locator('input[name="name"]').fill('Failure');
  await page.locator('input[name="email"]').fill('bad-address');
  await page.locator('input[name="password"]').fill(password);
  await page.getByRole('button', { name: 'Register', exact: true }).click();
  await page.getByText('Enter a valid email address.', { exact: true }).waitFor();
  await page.locator('input[name="email"]').fill('failure@example.test'); f.reject(true);
  await page.getByRole('button', { name: 'Register', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'We could not send' }).waitFor();
  await page.getByRole('link', { name: 'Continue to email verification / Resend Code' }).click();
  await page.getByText('Email delivery is not complete for', { exact: false }).waitFor();
  assert.ok(!(await page.locator('body').innerText()).includes('Verification email sent to'));
  // Advance both clocks without waiting for the real cooldown.
  f.reject(false); f.advance(61000); await page.clock.install(); await page.clock.fastForward(61000);
  await page.getByRole('button', { name: 'Resend Code', exact: true }).click();
  await page.getByText('A new verification email has been sent.', { exact: true }).waitFor();
  f.advance(900001); await page.clock.fastForward(900001);
  await page.getByText('Your verification code has expired. Please use Resend Code.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Resend Code', exact: true }).click();
  await page.getByText('A new verification email has been sent.', { exact: true }).waitFor();
  await page.getByLabel('Verification Code', { exact: true }).fill(f.messages.at(-1).code);
  await page.getByRole('button', { name: 'VERIFY', exact: true }).click();
  await page.waitForURL('**/student/dashboard');
  await context.close();
  assert.deepEqual(errors, []);
  console.log('validation, unauthorized access, delivery failure, resend and expiry passed; no browser errors');
} finally { await browser.close(); await f.close(); }
